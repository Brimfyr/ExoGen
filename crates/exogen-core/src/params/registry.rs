#[cfg(test)]
mod tests {
    use super::super::ParamGraph;
    use super::*;
    use std::cell::RefCell;
    use std::collections::BTreeSet;

    #[test]
    fn graph_builds_and_every_derivation_declares_what_it_reads() {
        let g = ParamGraph::new();
        for def in g.defs() {
            let Some(f) = def.derive else { continue };
            let accessed = RefCell::new(BTreeSet::new());
            {
                let ctx = Ctx::tracking(&g, &accessed);
                let v = f(&ctx);
                assert!(
                    def.ty.accepts(&def.ty.normalise(v.clone())),
                    "{} produced {:?}",
                    def.id,
                    v
                );
            }
            let declared: BTreeSet<String> = def.deps.iter().map(|s| s.to_string()).collect();
            let read = accessed.into_inner();
            let undeclared: Vec<&String> = read.iter().filter(|r| !declared.contains(*r)).collect();
            assert!(
                undeclared.is_empty(),
                "{} reads undeclared nodes {:?}",
                def.id,
                undeclared
            );
        }
    }

    #[test]
    fn ids_follow_the_group_dot_name_convention() {
        for def in nodes() {
            assert!(def.id.contains('.'), "{}", def.id);
            assert!(
                def.id
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '.' || c == '_'),
                "{}",
                def.id
            );
            assert!(!def.label.is_empty(), "{}", def.id);
        }
    }

    #[test]
    fn earth_defaults_derive_to_earth() {
        let g = ParamGraph::new();
        assert!((g.f64("body.gravity") - 9.82).abs() < 0.03);
        assert!((g.f64("body.escape_velocity") - 11_186.0).abs() < 30.0);
        assert_eq!(g.str("body.composition_class"), "rock");
        assert_eq!(g.str("rotation.mode"), "free");
        assert!((g.f64("atmosphere.equilibrium_temperature") - 254.6).abs() < 1.0);
        assert!(
            (g.f64("atmosphere.surface_temperature_mean") - 288.0).abs() < 4.0,
            "{}",
            g.f64("atmosphere.surface_temperature_mean")
        );
        assert_eq!(
            g.str("volatiles.working_liquid"),
            "none",
            "no inventory set yet"
        );
    }

    #[test]
    fn pinning_and_reset_behave() {
        let mut g = ParamGraph::new();
        g.set("volatiles.inventory", {
            let mut m = std::collections::BTreeMap::new();
            m.insert("H2O".to_string(), 2700.0);
            Value::Map(m)
        })
        .unwrap();
        assert_eq!(g.str("volatiles.working_liquid"), "water");
        assert_eq!(g.str("interior.tectonic_regime"), "mobile_lid");
        assert!(g.is_pinned("volatiles.inventory"));
        g.set("rotation.mode", "locked").unwrap();
        assert!(g.is_pinned("rotation.mode"));
        assert!((g.f64("rotation.effective_period") - g.f64("orbit.period")).abs() < 1.0);
        g.reset("rotation.mode");
        assert_eq!(g.str("rotation.mode"), "free");
        let overrides = g.overrides();
        assert!(overrides.contains_key("volatiles.inventory"));
        assert!(!overrides.contains_key("rotation.mode"));
        let mut g2 = ParamGraph::new();
        assert!(g2.apply_overrides(&overrides).is_empty());
        assert_eq!(g2.str("volatiles.working_liquid"), "water");
        assert_eq!(g.hash_of_group("body"), g2.hash_of_group("body"));
    }
}
